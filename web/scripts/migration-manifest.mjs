// Regenerates web/src/lib/dev/migrationFiles.ts from supabase/migrations.
//
// The Dev Dashboard compares the production ledger against the files in the
// folder. A Vercel build does not ship supabase/ inside the serverless
// bundle, so the file list is committed as a module and regenerated here.
// `pnpm migrations:manifest` runs this; migrationFiles.test.ts fails when
// the committed list drifts from the folder, so a forgotten regenerate is
// caught by the test gate, not by a wrong number on the dashboard.

import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const migrationsDir = path.resolve(here, '../../supabase/migrations');
const outFile = path.resolve(here, '../src/lib/dev/migrationFiles.ts');

const names = readdirSync(migrationsDir)
	.filter((f) => /^(\d{14}|\d{4}[a-z]?)_.+\.sql$/.test(f))
	.map((f) => f.replace(/\.sql$/, ''))
	.sort();

const body = [
	'// GENERATED by web/scripts/migration-manifest.mjs. Do not edit by hand.',
	'// Run `pnpm migrations:manifest` after adding a migration file.',
	'',
	'export const MIGRATION_FILES: readonly string[] = [',
	...names.map((n) => `\t'${n}',`),
	'];',
	'',
].join('\n');

writeFileSync(outFile, body);
console.log(`wrote ${names.length} migration names to ${path.relative(process.cwd(), outFile)}`);
